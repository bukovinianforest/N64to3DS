"""Dual-screen extension selection for the CIA builder.

A *profile* (``profiles/*.json``) describes one exact ROM revision: its
SHA-256, the extension that understands it, and the verified facts that
extension needs (symbol addresses, struct layout, name tables).  The builder
only enables an extension when the ROM's SHA-256 matches a profile; the
runtime then re-checks the header CRCs before using it.  Without a match the
CIA is built and runs exactly as without extensions.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .errors import BuildError
from .hm64_sprites import write_atlas
from .rom import NormalizedRom

PROFILES_DIR = Path(__file__).with_name("profiles")
ROMFS_PROFILE_PATH = Path("dualscreen") / "profile.txt"

# Extensions compiled into the runtime.  Keep in sync with
# runtime/3ds/DualScreen/ExtensionRegistry.cpp.
EXTENSIONS = {
    "harvest_moon_64": "Harvest Moon 64: pause-screen style inventory and clock",
}

# Default refresh interval in N64 frames.  Inventory, clock and position
# change at human speed; profiling under Azahar showed the update itself is
# cheap, so this mainly bounds RDRAM traffic.
DEFAULT_UPDATE_INTERVAL_FRAMES = 6


@dataclass(frozen=True)
class ExtensionSelection:
    extension: str
    profile_id: str
    profile_path: Path
    profile: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        return {
            "extension": self.extension,
            "profile": self.profile_id,
            "profile_path": str(self.profile_path),
            "source": self.profile.get("source"),
        }


def load_profiles(directory: Path = PROFILES_DIR) -> list[tuple[Path, dict[str, Any]]]:
    profiles = []
    for path in sorted(directory.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise BuildError(f"Invalid dual-screen profile {path}: {exc}") from exc
        for key in ("id", "extension", "rom"):
            if key not in data:
                raise BuildError(f"Dual-screen profile {path} is missing '{key}'.")
        profiles.append((path, data))
    return profiles


def select_extension(
    mode: str, rom: NormalizedRom, directory: Path = PROFILES_DIR
) -> ExtensionSelection | None:
    """Resolve ``--extensions`` (``off``, ``auto`` or an extension id)."""

    if mode == "off":
        return None
    if mode != "auto" and mode not in EXTENSIONS:
        raise BuildError(
            f"Unknown dual-screen extension {mode!r}.",
            hint="Use --extensions auto, off, or one of: " + ", ".join(sorted(EXTENSIONS)),
        )

    matches = [
        (path, profile)
        for path, profile in load_profiles(directory)
        if str(profile["rom"].get("sha256", "")).lower() == rom.sha256.lower()
        and profile["extension"] in EXTENSIONS
    ]
    if mode != "auto":
        matches = [(path, profile) for path, profile in matches if profile["extension"] == mode]
        if not matches:
            raise BuildError(
                f"Extension {mode!r} has no verified profile for this ROM (SHA-256 {rom.sha256}).",
                hint="Only exact ROM revisions with a profile in tools/n64to3ds/profiles are supported; "
                "addresses from another revision are never reused.",
            )
    if not matches:
        return None
    if len(matches) > 1:
        names = ", ".join(str(path.name) for path, _ in matches)
        raise BuildError(f"More than one dual-screen profile matches this ROM: {names}")
    path, profile = matches[0]
    return ExtensionSelection(
        extension=profile["extension"], profile_id=profile["id"], profile_path=path, profile=profile
    )


def flatten_profile(profile: dict[str, Any]) -> str:
    """Render a profile as the runtime's ``key=value`` format."""

    lines = [
        "# n64to3ds dual-screen profile (generated by the builder; do not edit)",
        f"id={profile['id']}",
        f"extension={profile['extension']}",
        f"rom.crc1={profile['rom']['crc1']}",
        f"rom.crc2={profile['rom']['crc2']}",
        f"rom.sha256={profile['rom']['sha256']}",
        f"update_interval_frames={profile.get('update_interval_frames', DEFAULT_UPDATE_INTERVAL_FRAMES)}",
    ]
    for name, address in sorted(profile.get("symbols", {}).items()):
        lines.append(f"symbol.{name}={address}")
    for field_name, layout in sorted(profile.get("player_layout", {}).items()):
        lines.append(f"layout.player.{field_name}.offset={layout['offset']}")
        lines.append(f"layout.player.{field_name}.type={layout['type']}")
        lines.append(f"layout.player.{field_name}.count={layout['count']}")
    for table, names in sorted(profile.get("names", {}).items()):
        for key, value in sorted(names.items(), key=lambda item: int(item[0])):
            lines.append(f"name.{table}.{key}={_single_line(value)}")
    for index, info in sorted(profile.get("maps", {}).items(), key=lambda item: int(item[0])):
        for key, value in sorted(info.items()):
            lines.append(f"map.{index}.{key}={_single_line(str(value))}")
    for key, value in sorted(profile.get("inventory_swap", {}).items()):
        lines.append(f"inventory_swap.{key}={value}")
    if "map_tile_size" in profile:
        lines.append(f"map_tile_size={profile['map_tile_size']}")
    return "\n".join(lines) + "\n"


def write_romfs_profile(selection: ExtensionSelection, romfs_dir: Path, rom: NormalizedRom) -> Path:
    destination = romfs_dir / ROMFS_PROFILE_PATH
    destination.parent.mkdir(parents=True, exist_ok=True)
    text = flatten_profile(selection.profile)
    sprites = selection.profile.get("sprites")
    if sprites:
        # Game graphics are decoded from the user's ROM into the RomFS only.
        text += "\n".join(write_atlas(rom.data, sprites, romfs_dir)) + "\n"
    destination.write_text(text, encoding="utf-8")
    return destination


def _single_line(value: str) -> str:
    text = str(value)
    # The runtime splits on the first '=' and treats '#' as a comment.
    if "\n" in text or "#" in text:
        raise BuildError(f"Profile value {text!r} cannot be written to the runtime format.")
    return text
